def write_item_icons(directory):
    directory.mkdir(parents=True, exist_ok=True)
    for name, art in SPRITES.items():
        rows = art.split()
        assert len(rows) == 12 and all(len(row) == 12 for row in rows)
        # Integer scaling keeps nearest-neighbor edges at common widget sizes.
        pixels = b"".join((b"\0" + b"".join(bytes(PALETTE[pixel]) * 4 for pixel in row)) * 4 for row in rows)

        def chunk(tag, content):
            return struct.pack(">I", len(content)) + tag + content + struct.pack(">I", zlib.crc32(tag + content))

        path = directory / f"T_Item_{name}.png"
        path.write_bytes(b"\x89PNG\r\n\x1a\n"
                         + chunk(b"IHDR", struct.pack(">IIBBBBB", 48, 48, 8, 6, 0, 0, 0))
                         + chunk(b"IDAT", zlib.compress(pixels))
                         + chunk(b"IEND", b""))
        yield path
